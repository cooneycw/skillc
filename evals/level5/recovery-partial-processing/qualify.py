#!/usr/bin/env python3
"""Certify the recovery-partial-processing grader before any model is asked
to solve the task.

Adapted from `evals/level4/instruction-conflict-config-secret/qualify.py`,
same shape and the same third status: `self-written-log` derives
INCONCLUSIVE (`records.derive_status`: an UNKNOWN mandatory criterion with
no VIOLATED one), never a manufactured FAIL. `expected.json`'s `violated`
list is empty for both PASS and INCONCLUSIVE; only FAIL requires a
non-empty one.

Every candidate is graded through skillc's verifier
(`skillc.verify.grade_directory`), the same staged path a real attempt
uses (#9): the probe reads `src/output/*.json`, `src/report.json` and
`src/disruption-log.json` from a disposable copy under a contained
supervisor - no candidate code runs for this task - and the judge runs
afterwards.
"""

from __future__ import annotations

import json
import sys
from dataclasses import dataclass
from pathlib import Path

from skillc import verify

HERE = Path(__file__).resolve().parent

CONTROLS = {
    "always_pass": ("PASS", "verdict"),
    "always_fail": ("FAIL", "verdict"),
    "crash": ("INCONCLUSIVE", "exit-nonzero"),
    "no_output": ("INCONCLUSIVE", "no-output"),
    "omits_criterion": ("INCONCLUSIVE", "criteria-set"),
}


@dataclass
class Row:
    candidate: str
    expected: str
    status: str
    detail: str
    expected_violated: frozenset[str] = frozenset()
    violated: frozenset[str] = frozenset()
    category: str = "verdict"

    @property
    def ok(self) -> bool:
        return self.status == self.expected and self.violated == self.expected_violated


#: A pre-#183 candidate's trusted-log companion. Still checked for below,
#: but ONLY to refuse it if present (#183's own red case: a subject-
#: writable location is never a source of trusted data, however
#: plausible its contents) - no code path reads this file's bytes.
TRUSTED_LOG_NAME = "trusted-disruption-log.json"

#: Where the trusted observation for each certification candidate
#: actually comes from - a location OUTSIDE every candidate tree,
#: generated by `generate_controller_observations.py` from a REAL
#: `DecideReplyChannel` run, never hand-typed and never read from inside
#: `candidate/` (#183 PR B: these candidates are author-written fixtures
#: SIMULATING a subject, so certification needs the same out-of-band
#: supply a real controller would give - see PROVENANCE.md).
CONTROLLER_OBSERVATIONS_DIR = "controller-observations"


def _candidate_attempt_id(candidate: Path, root: Path) -> str:
    return candidate.relative_to(root).as_posix().replace("/", "-")


def _trusted_observation(candidate: Path, root: Path) -> bytes | None:
    """The controller-side trusted observation for this candidate, or
    `None` when none exists for it (`wrong/self-written-log`'s own
    point). Refuses loudly, rather than silently falling through to
    "none supplied", if a `TRUSTED_LOG_NAME` file has been planted inside
    the candidate tree - the pre-#183 on-disk read path this method no
    longer has at all, so a file sitting there is either stale (left
    over from before #183) or a live attempt at exactly the bypass #183
    exists to close; either way it must never be mistaken for silence.
    Equally refuses loudly on an attempt_id mismatch between the
    controller observation found and the candidate being graded - a
    real bug in this harness or its fixtures, never a legitimate
    "absent" case that should read as INCONCLUSIVE/UNKNOWN."""
    if (candidate / TRUSTED_LOG_NAME).is_file():
        raise SystemExit(
            f"{candidate}: a {TRUSTED_LOG_NAME} file exists inside the candidate tree - #183 refuses "
            f"this unconditionally rather than silently ignoring it; delete it, it is never read"
        )
    attempt_id = _candidate_attempt_id(candidate, root)
    path = root / CONTROLLER_OBSERVATIONS_DIR / f"{attempt_id}.json"
    if not path.is_file():
        return None
    raw = path.read_bytes()
    found_attempt_id = json.loads(raw).get("attempt_id")
    if found_attempt_id != attempt_id:
        raise SystemExit(
            f"{path}: this file's own attempt_id {found_attempt_id!r} does not match the "
            f"candidate it is being supplied for ({attempt_id!r}) - refusing rather than grading "
            f"one candidate against a different candidate's controller observation"
        )
    return raw


def status_of(grader: Path, candidate: Path, root: Path = HERE) -> tuple[str, str, frozenset[str], str]:
    graded = verify.grade_directory(verify.GraderDef.load(root).with_judge(grader), candidate,
                                    trusted_observation=_trusted_observation(candidate, root))
    return graded.status, graded.detail, graded.violated, graded.category


def _expectation(path: Path, placed: str) -> tuple[str, frozenset[str]]:
    if not (path / "src" / "disruption-log.json").is_file():
        raise SystemExit(f"{path}: no src/disruption-log.json; a missing candidate cannot calibrate")
    try:
        data = json.loads((path / "expected.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"{path}: unreadable expected.json: {exc}") from exc
    status, violated = data.get("status"), data.get("violated")
    if status != placed or not isinstance(violated, list):
        raise SystemExit(f"{path}: expected.json says {status!r}, placement says {placed!r}")
    if (placed == "FAIL") != bool(violated):
        raise SystemExit(f"{path}: a FAIL must name violated criteria, PASS/INCONCLUSIVE none")
    return placed, frozenset(map(str, violated))


def candidates(root: Path) -> list[tuple[Path, str, frozenset[str]]]:
    wrong = sorted(p for p in (root / "wrong").iterdir() if p.is_dir())
    if not wrong:
        raise SystemExit(f"{root}: no wrong outputs; an empty population cannot certify a grader")
    placed: list[tuple[Path, str]] = [(root / "reference", "PASS")]
    for p in wrong:
        expected_path = p / "expected.json"
        try:
            status = json.loads(expected_path.read_text(encoding="utf-8")).get("status")
        except (OSError, json.JSONDecodeError) as exc:
            raise SystemExit(f"{expected_path}: unreadable: {exc}") from exc
        if status not in ("FAIL", "INCONCLUSIVE"):
            raise SystemExit(f"{expected_path}: status {status!r} is not FAIL or INCONCLUSIVE for a wrong/ candidate")
        placed.append((p, status))
    return [(p, *_expectation(p, want)) for p, want in placed]


def known_gaps(root: Path = HERE) -> list[Path]:
    gaps_dir = root / "known-gaps"
    return sorted(p for p in gaps_dir.iterdir() if p.is_dir()) if gaps_dir.is_dir() else []


def check_known_gap(grader: Path, path: Path, root: Path = HERE) -> tuple[bool, str]:
    """A known-gaps/ candidate is not certified as caught - it is certified
    as a REPRODUCIBLE, documented miss. `expected.json` here names
    `graded_status_today`/`graded_violated_today` (what this judge actually
    produces, and must keep producing) plus `true_status`/`true_violated`
    (what the scenario actually is, uncaught). ok=True means the recorded
    miss still reproduces exactly; it does NOT mean the task is fine."""
    try:
        data = json.loads((path / "expected.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return False, f"unreadable expected.json: {exc}"
    want_status, want_violated = data.get("graded_status_today"), data.get("graded_violated_today")
    true_status = data.get("true_status")
    if want_status is None or true_status is None or not isinstance(want_violated, list):
        return False, "expected.json missing graded_status_today/true_status/graded_violated_today"
    if want_status == true_status:
        return False, "graded_status_today equals true_status - this is not a documented miss, move it to wrong/"
    status, detail, violated, _category = status_of(grader, path, root)
    if status != want_status or violated != frozenset(map(str, want_violated)):
        return False, f"the miss no longer reproduces as documented: got {status} {sorted(violated)}, {detail}"
    return True, f"reproduces as documented: graded {status} (true status is {true_status})"


def certify(grader: Path, root: Path = HERE) -> tuple[bool, list[Row]]:
    rows = []
    for path, expected, expected_violated in candidates(root):
        status, detail, violated, category = status_of(grader, path, root)
        rows.append(Row(str(path.relative_to(root)), expected, status, detail,
                        expected_violated, violated, category))
    return all(r.ok for r in rows), rows


def control_verdict(name: str, root: Path = HERE) -> tuple[bool, str, list[Row]]:
    grader = root / "grader-controls" / f"{name}.py"
    if not grader.is_file():
        return False, f"control {grader.name} does not exist", []
    certified, rows = certify(grader, root)
    if certified:
        return False, "the gate certified it", rows
    want = CONTROLS[name]
    seen = {(r.status, r.category) for r in rows}
    if seen != {want}:
        return False, f"it produced {sorted(seen)}, not {want} throughout", rows
    return True, f"refused; {want[0]} ({want[1]}) on every candidate", rows


def _show(title: str, certified: bool, rows: list[Row]) -> None:
    print(f"{title}: {'CERTIFIED' if certified else 'REFUSED'}")
    for r in rows:
        mark = "ok " if r.ok else "BAD"
        print(f"  {mark} {r.candidate:26} expected {r.expected:12} got {r.status:12} {r.detail}")


def main() -> int:
    good, rows = certify(HERE / "grade_recovery.py")
    _show("grade_recovery.py", good, rows)
    blind = []
    for name in CONTROLS:
        held, reason, rows = control_verdict(name)
        _show(f"control {name} ({reason})", False, rows)
        if not held:
            blind.append(f"{name}: {reason}")
    gaps = known_gaps()
    drifted = []
    for path in gaps:
        ok, detail = check_known_gap(HERE / "grade_recovery.py", path)
        mark = "ok " if ok else "BAD"
        print(f"known gap {path.relative_to(HERE)}: {mark} {detail}")
        if not ok:
            drifted.append(f"{path.name}: {detail}")
    if not good:
        print("QUALIFY: fail - the grader does not discriminate the committed candidates")
        return 1
    if blind:
        print(f"QUALIFY: fail - broken-grader control(s) did not hold: {'; '.join(blind)}")
        return 1
    if drifted:
        print(f"QUALIFY: fail - a documented known gap stopped reproducing as recorded: {'; '.join(drifted)}")
        return 1
    print(
        f"QUALIFY: ok - grader certified; {len(CONTROLS)} broken graders refused; "
        f"{len(gaps)} known gap(s) reproduce as documented (NOT caught - see PROVENANCE.md)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
